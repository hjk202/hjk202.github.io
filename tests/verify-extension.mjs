import { cpSync, mkdirSync, readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import process from 'node:process';
import { log } from 'node:console';

const root = resolve('.');
const isolated = resolve('.cache', `extension-${Date.now()}`);
const snapshot = (directory) => Object.fromEntries(readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
  const path = join(directory, entry.name);
  return entry.isDirectory() ? Object.entries(snapshot(path)) : [[path, createHash('sha256').update(readFileSync(path)).digest('hex')]];
}));
const before = snapshot('src');
mkdirSync(isolated, { recursive: true });
cpSync('src', join(isolated, 'src'), { recursive: true });
if (existsSync('public')) cpSync('public', join(isolated, 'public'), { recursive: true });
for (const file of ['package.json', 'astro.config.mjs', 'tsconfig.json']) cpSync(file, join(isolated, file));
const extra = join(isolated, 'src/modules/observatory');
mkdirSync(extra);
for (const file of readdirSync('tests/fixtures/observatory')) cpSync(join('tests/fixtures/observatory', file), join(extra, file.replace(/\.fixture$/, '')));
const astroPackage = JSON.parse(readFileSync('node_modules/astro/package.json', 'utf8'));
const cli = resolve('node_modules/astro', astroPackage.bin.astro);
execFileSync(process.execPath, [cli, 'check'], { cwd: isolated, stdio: 'inherit', env: { ...process.env, ASTRO_TELEMETRY_DISABLED: '1' } });
execFileSync(process.execPath, [cli, 'build'], { cwd: isolated, stdio: 'inherit', env: { ...process.env, ASTRO_TELEMETRY_DISABLED: '1' } });
const output = join(isolated, 'dist');
const index = JSON.parse(readFileSync(join(output, 'search-index.json'), 'utf8'));
assert.equal(index.modules.length, 5);
assert.equal(index.modules.at(-1).id, 'observatory');
assert.equal(index.modules.at(-1).count, 1);
assert.ok(index.results.some((result) => result.url === '/observatory/' && result.title === 'Extension verification'));
const home = readFileSync(join(output, 'index.html'), 'utf8');
assert.equal((home.match(/<a\b[^>]*\bdata-compass-link(?:=|\s|>)/g) ?? []).length, 5);
const polygon = /class="compass-outline" points="([^"]+)"/.exec(home)?.[1];
assert.equal(polygon?.split(' ').length, 5);
assert.ok(readFileSync(join(output, 'observatory/index.html'), 'utf8').includes('Extension verification'));
assert.deepEqual(snapshot('src'), before, 'Original framework and modules must remain unchanged');
assert.equal(readdirSync(join(root, 'src/modules')).length, 4);
writeFileSync('.cache/extension-output.txt', output);
log(`Isolated fifth-module acceptance passed: ${output}`);
